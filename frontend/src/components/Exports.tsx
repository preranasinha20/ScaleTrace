import { Download } from "lucide-react";
import { useState } from "react";
import { Notice } from "./ui";

const EXPORTS = [
  { id: "report-html", title: "Diagnosis report (HTML)", text: "Self-contained report with findings, risk paths and diagnoses." },
  { id: "report-md", title: "Diagnosis report (Markdown)", text: "The same report as Markdown, for notes or pull requests." },
  { id: "diagnosis-json", title: "Diagnosis (JSON)", text: "Full machine-readable diagnosis, including the static report." },
  { id: "findings-csv", title: "Findings (CSV)", text: "One row per finding: rule, severity, status, location, function, endpoint." },
  { id: "graph-json", title: "Knowledge graph (JSON)", text: "All nodes and edges with their attributes." },
  {
    id: "graph-html",
    title: "Knowledge graph (HTML)",
    text: "Interactive graph page. When opened, it loads the vis-network library from unpkg.com.",
  },
];

export function Exports({ download, description }: { download: (format: string) => Promise<void>; description: string }) {
  const [busy, setBusy] = useState<string | null>(null);
  const [status, setStatus] = useState<{ id: string; ok: boolean; text: string } | null>(null);

  const run = async (id: string, title: string) => {
    setBusy(id);
    setStatus(null);
    try {
      await download(id);
      setStatus({ id, ok: true, text: `${title} downloaded.` });
    } catch (e) {
      setStatus({ id, ok: false, text: `${title} failed: ${(e as Error).message}` });
    } finally {
      setBusy(null);
    }
  };

  return (
    <div>
      <p className="muted small">
        Files are generated by the backend from the analysis shown above, using the same settings: {description}.
      </p>
      <div className="exports">
        {EXPORTS.map((x) => (
          <div key={x.id} className="export">
            <h3>{x.title}</h3>
            <p>{x.text}</p>
            <div>
              <button type="button" className="btn" disabled={busy !== null} onClick={() => run(x.id, x.title)}>
                <Download size={14} aria-hidden />
                {busy === x.id ? "Preparing..." : "Download"}
              </button>
            </div>
          </div>
        ))}
      </div>
      <div style={{ marginTop: 12 }} aria-live="polite">
        {status && <Notice tone={status.ok ? "ok" : "error"}>{status.text}</Notice>}
      </div>
    </div>
  );
}
